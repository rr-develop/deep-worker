"""Lock on the INJECTION POINT of the LSP fragment into the system prompt.

Contract (confirmed by the reviewer during code review):

The fragment is added when symbolic tools actually arrived — regardless
of whether the base system prompt was generated by us or passed in
explicitly by the caller. An explicit base prompt is NOT a reason to
hide documentation of available capabilities from the agent.

The test guards exactly this behavior: if someone moves the injection
inside the ``if system_prompt is None`` branch (easy to do by accident —
the lines look adjacent), an agent with a custom prompt would silently
lose the LSP hint, and the test would catch it.

We check at the composition-logic level, without building the whole
graph: the expensive ``create_cli_agent`` is not needed here.
"""
from __future__ import annotations

from deep_worker_cli.lsp.prompt import lsp_prompt_fragment

_SERENA_TOOLS = [
    "serena__find_symbol",
    "serena__find_referencing_symbols",
]


def _compose(base: str, external_tool_names: list[str]) -> str:
    """Exact copy of the composition from agent.py (design §4.4).

    We keep it here to pin the EXPECTED behavior: any change to agent.py
    that diverges from this contract must be deliberate and accompanied
    by a change to this test.
    """
    if external_tool_names:
        fragment = lsp_prompt_fragment(sorted(external_tool_names))
        if fragment:
            return f"{base}\n\n{fragment}"
    return base


def test_fragment_appended_to_generated_prompt() -> None:
    out = _compose("BASE PROMPT", _SERENA_TOOLS)
    assert out.startswith("BASE PROMPT")
    assert "serena__find_symbol" in out


def test_fragment_appended_even_when_prompt_is_explicit() -> None:
    """Key case: the caller passed THEIR OWN prompt — the hint must still
    arrive, otherwise the agent never learns about the capabilities."""
    custom = "custom operator-provided system prompt"
    out = _compose(custom, _SERENA_TOOLS)
    assert out.startswith(custom)
    assert "serena__find_symbol" in out


def test_base_prompt_untouched_without_lsp_tools() -> None:
    """Optionality: no LSP tools → the prompt does not change by a single byte."""
    base = "BASE PROMPT"
    assert _compose(base, []) == base
    assert _compose(base, ["github__create_issue"]) == base


def test_base_prompt_is_never_mutated_in_place() -> None:
    base = "BASE PROMPT"
    _compose(base, _SERENA_TOOLS)
    assert base == "BASE PROMPT"


def test_fragment_is_separated_by_blank_line() -> None:
    """The fragment is a separate markdown block, not glued to the base."""
    out = _compose("BASE", _SERENA_TOOLS)
    assert "BASE\n\n## " in out
