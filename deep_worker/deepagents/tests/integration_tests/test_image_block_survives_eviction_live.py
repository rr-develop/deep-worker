def _remaining(deadline: float) -> float:
    """Seconds left before the shared deadline (never negative)."""
    return max(0.0, deadline - time.monotonic())


class InotifyWatch:
    """Minimal event-driven watch on a directory, stdlib only.

    Used instead of a polling loop: `wait()` blocks in `select` until the kernel
    reports activity in the watched directory, so the test never re-reads on a
    timer. If inotify is unavailable the watch reports itself unsupported and
    the caller skips the test -- falling back to a sleep/retry loop would
    reintroduce exactly the polling this exists to avoid.
    """

    _IN_MODIFY = 0x00000002
    _IN_CREATE = 0x00000100
    _IN_MOVED_TO = 0x00000080

    def __init__(self, directory: Path) -> None:
        self._fd = -1
        self._libc = None
        try:
            libc = ctypes.CDLL("libc.so.6", use_errno=True)
            fd = libc.inotify_init1(os.O_CLOEXEC)
            if fd < 0:
                return
            mask = self._IN_MODIFY | self._IN_CREATE | self._IN_MOVED_TO
            if libc.inotify_add_watch(fd, str(directory).encode(), mask) < 0:
                os.close(fd)
                return
            self._fd = fd
            self._libc = libc
        except (OSError, AttributeError):
            self._fd = -1

    @property
    def supported(self) -> bool:
        return self._fd >= 0

    def wait(self, timeout: float) -> bool:
        """Block until activity or `timeout`. True if something happened."""
        if self._fd < 0:  # pragma: no cover - callers skip when unsupported
            raise RuntimeError("inotify unavailable")
        readable, _, _ = select.select([self._fd], [], [], timeout)
        if not readable:
            return False
        try:
            os.read(self._fd, 64 * 1024)  # drain; the content is irrelevant
        except OSError:
            return False
        return True

    def close(self) -> None:
        if self._fd >= 0:
            os.close(self._fd)
            self._fd = -1


def _make_nonce(length: int = 6) -> str:
    """A fresh codeword, so a pass can never come from memorised content."""
    return "".join(secrets.choice(_NONCE_ALPHABET) for _ in range(length))


def _render_nonce_png(nonce: str, *, scale: int = 22, pad: int = 40, noise_rows: int = 45) -> bytes:
    """Render `nonce` as a black-on-white PNG using only the stdlib.

    The bitmap carries the codeword as large blocky glyphs, plus a band of
    incompressible random noise underneath. The noise exists purely to make the
    encoded payload large: PNG is losslessly compressed, so flat glyph art alone
    would shrink to a few kilobytes and would never cross the eviction
    threshold, leaving the very code path under test unexercised.
    """
    glyph_w, glyph_h, gap = 5, 7, 1
    cols = len(nonce) * (glyph_w + gap) - gap
    width = cols * scale + pad * 2
    height = glyph_h * scale + pad * 2 + noise_rows

    # Start with a white canvas, then stamp black pixels for glyph bits.
    rows = [bytearray(b"\xff" * (width * 3)) for _ in range(height)]
    for char_index, char in enumerate(nonce):
        glyph = _GLYPHS[char]
        x_origin = char_index * (glyph_w + gap) * scale + pad
        for row_index, bits in enumerate(glyph):
            for col_index, bit in enumerate(bits):
                if bit != "1":
                    continue
                for dy in range(scale):
                    y = pad + row_index * scale + dy
                    row = rows[y]
                    start = (x_origin + col_index * scale) * 3
                    for dx in range(scale):
                        offset = start + dx * 3
                        row[offset : offset + 3] = b"\x00\x00\x00"

    # Random noise band below the glyphs: incompressible, so it reliably pushes
    # the encoded payload over the eviction threshold without touching the
    # codeword area the model has to read.
    noise_start = glyph_h * scale + pad * 2
    for y in range(noise_start, height):
        rows[y] = bytearray(secrets.token_bytes(width * 3))

    raw = b"".join(b"\x00" + bytes(row) for row in rows)

    def chunk(tag: bytes, payload: bytes) -> bytes:
        body = tag + payload
        return struct.pack(">I", len(payload)) + body + struct.pack(">I", zlib.crc32(body))

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 6))
        + chunk(b"IEND", b"")
    )


_TRANSCRIPT_END = "=" * 60


def _committed_answer(transcript: str) -> str | None:
    """Extract the model's final committed reply, or None if there is not one.

    The agent's LOG echoes the prompt verbatim, and the prompt itself contains
    the string NO_IMAGE_VISIBLE, so scanning the whole transcript for that token
    would match before the model has said anything. Only the session history is
    authoritative, and only after the last `[ASSISTANT]` marker; the reply runs
    from the end of that marker's header line to the trailing rule.

    Returning None (rather than "") is what lets callers distinguish "the agent
    answered nothing meaningful" from "the agent never answered at all", so a
    crash or timeout cannot masquerade as a successful negative result.
    """
    _, marker, tail = transcript.rpartition("[ASSISTANT]")
    if not marker:
        return None

    # Drop the rest of the marker line (the timestamp).
    _, newline, body = tail.partition("\n")
    if not newline:
        return None

    body = body.split(_TRANSCRIPT_END)[0].strip()
    return body or None


def _build_mutant_tree(destination: Path) -> None:
    """Materialize an isolated tree whose image preservation is disabled.

    The production worktree is NEVER modified. `deep-worker --dev` resolves its
    target from `DEEP_WORKER_DEV_TREE_ROOT_OVERRIDE` (a documented testing hook)
    and rebuilds PYTHONPATH relative to that root, so pointing it at this copy
    is enough to make the agent import the mutated module.

    The tree is assembled from symlinks to the real one, except for the single
    package that has to differ; within that package only `filesystem.py` is a
    real file, and only one line of it differs. Everything else the agent uses
    is shared, so a behavioural difference between #26 and #27 cannot come from
    anywhere but that line.
    """
    real_root = Path(__file__).resolve().parents[4]
    real_deepagents = Path(__file__).resolve().parents[2]

    source = real_deepagents / "deepagents" / "middleware" / "filesystem.py"
    original = source.read_text()
    marker = "        used_budget += payload_len\n        preserved.append((index, block))"
    if marker not in original:
        pytest.fail("mutation target not found -- update the marker in _build_mutant_tree")
    mutated = original.replace(
        marker,
        "        used_budget += payload_len\n        evictable.append((index, block))",
    )

    def mirror(real_dir: Path, out_dir: Path, real_children: set[str]) -> None:
        """Symlink everything in `real_dir` except the names we must own.

        `__pycache__` is never symlinked: a shared cache directory would let the
        mutant's imports write bytecode straight into the production tree,
        corrupting cache state for concurrently running agents. Each mirrored
        package gets its own empty cache directory instead.
        """
        out_dir.mkdir(parents=True, exist_ok=True)
        out_dir.chmod(0o755)
        for entry in real_dir.iterdir():
            if entry.name in real_children or entry.name == "__pycache__":
                continue
            (out_dir / entry.name).symlink_to(entry)

    # <root>/deep_worker/deepagents/deepagents/middleware/filesystem.py
    mirror(real_root, destination, {"deep_worker"})
    mirror(real_root / "deep_worker", destination / "deep_worker", {"deepagents", "deep_worker_cli"})

    # The launcher resolves "this tree" with `readlink -f` on its own path, so a
    # symlinked launcher would resolve straight back to the real tree and the
    # mutation would be silently ignored. It has to be a real file here.
    mirror(
        real_root / "deep_worker" / "deep_worker_cli",
        destination / "deep_worker" / "deep_worker_cli",
        {"deep-worker", "deepagents"},
    )
    real_launcher = real_root / "deep_worker" / "deep_worker_cli" / "deep-worker"
    copied_launcher = destination / "deep_worker" / "deep_worker_cli" / "deep-worker"
    shutil.copy2(real_launcher, copied_launcher)
    copied_launcher.chmod(0o755)

    # `deep_worker_cli/deepagents` is itself a symlink to ../deepagents/deepagents,
    # and it comes FIRST on the launcher's PYTHONPATH. Mirroring it verbatim would
    # point it back into the real tree, so every import would resolve to the
    # unmutated package and the mutation would be silently ignored — the same
    # class of false pass the launcher copy above guards against.
    (destination / "deep_worker" / "deep_worker_cli" / "deepagents").symlink_to(
        destination / "deep_worker" / "deepagents" / "deepagents"
    )
    mirror(
        real_deepagents,
        destination / "deep_worker" / "deepagents",
        {"deepagents"},
    )
    mirror(
        real_deepagents / "deepagents",
        destination / "deep_worker" / "deepagents" / "deepagents",
        {"middleware"},
    )
    mirror(
        real_deepagents / "deepagents" / "middleware",
        destination / "deep_worker" / "deepagents" / "deepagents" / "middleware",
        {"filesystem.py"},
    )

    target = destination / "deep_worker" / "deepagents" / "deepagents" / "middleware" / "filesystem.py"
    target.write_text(mutated)
    target.chmod(0o644)

    # Private bytecode caches for every package the mutant owns, so an import
    # can never resolve __pycache__ through a symlink into the real tree.
    for package_dir in _mutant_package_dirs(destination):
        cache = package_dir / "__pycache__"
        cache.mkdir(exist_ok=True)
        cache.chmod(0o755)

    _assert_cache_dirs_are_private(destination)
    _assert_tree_is_mutated(destination)


def _mutant_package_dirs(root: Path) -> list[Path]:
    """Directories the mutant tree owns outright (never symlinks to the real one)."""
    deepagents_root = root / "deep_worker" / "deepagents" / "deepagents"
    return [deepagents_root, deepagents_root / "middleware"]


def _assert_cache_dirs_are_private(root: Path) -> None:
    """No writable/cache location in the mutant may resolve into the real tree.

    A symlinked `__pycache__` would let the mutant's imports write bytecode into
    the production package, corrupting cache state for agents running normally.
    """
    real_deepagents = Path(__file__).resolve().parents[2].resolve()

    for package_dir in _mutant_package_dirs(root):
        assert package_dir.is_dir() and not package_dir.is_symlink(), f"{package_dir} is not owned by the mutant tree"
        cache = package_dir / "__pycache__"
        assert cache.is_dir(), f"missing private cache dir: {cache}"
        assert not cache.is_symlink(), f"{cache} is a symlink"
        resolved = cache.resolve()
        assert not resolved.is_relative_to(real_deepagents), f"{cache} resolves into the real package at {resolved}"
        assert resolved.is_relative_to(root.resolve()), f"{cache} escapes the mutant tree to {resolved}"


def _assert_tree_is_mutated(root: Path) -> None:
    """Prove an agent launched against `root` really imports the mutated module.

    Without this, a mis-built tree would silently fall back to the real package
    and #27 would "pass" while proving nothing -- the exact failure mode that
    already bit this test once via PYTHONPATH.
    """
    script_dir = root / "deep_worker" / "deep_worker_cli"
    parent_dir = root / "deep_worker"
    env = {k: v for k, v in os.environ.items() if k not in ("PYTHONPATH",)}
    env["PYTHONPATH"] = os.pathsep.join(
        [str(script_dir), str(parent_dir / "deepagents"), str(parent_dir)]
    )
    # Defense in depth: even with private cache dirs, never emit bytecode while
    # probing a throwaway tree.
    env["PYTHONDONTWRITEBYTECODE"] = "1"

    probe = (
        "import inspect;"
        "import deepagents.middleware.filesystem as f;"
        "print(f.__file__);"
        "print('preserved.append((index, block))' in "
        "inspect.getsource(f._classify_content_blocks))"
    )
    result = subprocess.run(
        [sys.executable, "-c", probe],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
        env=env,
        cwd=tempfile.gettempdir(),  # never the real package directory
    )
    lines = result.stdout.strip().splitlines()
    if len(lines) != 2:
        pytest.fail(f"could not probe mutant tree: {result.stdout!r} {result.stderr[-500:]!r}")

    imported_from, still_preserves = lines
    assert imported_from.startswith(str(root)), f"agent would import {imported_from}, not the mutant"
    assert still_preserves == "False", "mutant tree still contains the preservation branch"


def _read_image_shaped_result(png_bytes: bytes, name: str) -> list[dict]:
    """The exact content shape the `read_image` tool produces."""
    encoded = base64.b64encode(png_bytes).decode("ascii")
    return [
        {"type": "text", "text": f"Image: {name}, image/png, {len(png_bytes)} bytes"},
        {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{encoded}"}},
    ]


class TestGeneratedNoncedImage:
    """The generator itself must be sound, or the live proof means nothing."""

    def test_generated_png_crosses_the_eviction_threshold(self) -> None:
        """The fixture image must actually be large enough to trigger eviction.

        Without this guard the live test could pass trivially by never entering
        the eviction path it is supposed to prove.
        """
        nonce = _make_nonce()
        content = _read_image_shaped_result(_render_nonce_png(nonce), "nonce.png")

        # Pre-fix, this whole structure was stringified and measured; that is
        # what destroyed the image. Assert the payload really is over the bar
        # for the default limit of 20000 tokens * 4 chars per token.
        assert len(str(content)) > NUM_CHARS_PER_TOKEN * DEFAULT_TOOL_TOKEN_LIMIT

    def test_image_block_survives_classification(self) -> None:
        """The middleware keeps the image and never writes its bytes to the file."""
        nonce = _make_nonce()
        content = _read_image_shaped_result(_render_nonce_png(nonce), "nonce.png")

        preserved, evictable, _ = _classify_content_blocks(content)

        assert len(preserved) == 1
        assert preserved[0][1]["type"] == "image_url"
        # The base64 payload must not leak into the evicted text.
        assert "base64" not in _evictable_content_str(content, evictable)


class TestMutantTreeIsolation:
    """The #27 mutant tree must never be able to write into the real package."""

    def test_cache_dirs_never_resolve_into_the_real_package(self, tmp_path):
        root = tmp_path / "mutant"
        _build_mutant_tree(root)

        real_deepagents = Path(__file__).resolve().parents[2].resolve()
        for package_dir in _mutant_package_dirs(root):
            cache = package_dir / "__pycache__"
            assert cache.is_dir()
            assert not cache.is_symlink()
            assert not cache.resolve().is_relative_to(real_deepagents)

    def test_owned_directories_in_the_mutant_package_stay_local(self, tmp_path):
        """Directories the mutant OWNS stay inside the mutant tree.

        Deliberately scoped: symlinked directories are skipped, so this does NOT
        claim that every traversable writable path is contained -- a symlinked
        subpackage still points at the real tree and is writable in principle.
        What makes that safe is not this assertion but the two mechanisms above:
        `__pycache__` is never symlinked (the only thing Python writes during an
        import), and PYTHONDONTWRITEBYTECODE=1 suppresses the writes anyway.
        This test pins the narrower property those mechanisms rely on.
        """
        root = tmp_path / "mutant"
        _build_mutant_tree(root)
        real_deepagents = Path(__file__).resolve().parents[2].resolve()

        for package_dir in _mutant_package_dirs(root):
            for entry in package_dir.iterdir():
                if entry.is_dir() and not entry.is_symlink():
                    assert not entry.resolve().is_relative_to(real_deepagents)

    def test_only_filesystem_py_differs_from_the_real_package(self, tmp_path):
        """Everything else is a symlink, so nothing else can drift."""
        root = tmp_path / "mutant"
        _build_mutant_tree(root)

        middleware = root / "deep_worker" / "deepagents" / "deepagents" / "middleware"
        real_files = [
            entry.name
            for entry in middleware.iterdir()
            if entry.is_file() and not entry.is_symlink()
        ]
        assert real_files == ["filesystem.py"]


class TestCommittedAnswerExtractor:
    """`_committed_answer` decides pass/fail for #26 and #27, so pin it here.

    These run ungated: if the extractor is wrong, both live tests can silently
    pass or fail for reasons unrelated to image preservation.
    """

    RULE = "=" * 60

    def _transcript(self, body: str) -> str:
        return (
            "[USER] - Aug 05, 9:00:00.000am\n"
            "Use the read_image tool ... reply NO_IMAGE_VISIBLE.\n"
            "------------------------------------------------------------\n"
            f"[ASSISTANT] - Aug 05, 9:00:10.000am\n{body}\n"
            f"{self.RULE}\n"
        )

    def test_returns_none_when_no_assistant_marker(self):
        """A crash or timeout leaves no reply: that must be distinguishable."""
        assert _committed_answer("[USER] - now\nsomething\n") is None

    def test_returns_none_for_empty_body(self):
        assert _committed_answer(self._transcript("   ")) is None

    def test_extracts_the_reply_only(self):
        assert _committed_answer(self._transcript("ABC123")) == "ABC123"

    def test_ignores_no_image_visible_echoed_in_the_prompt(self):
        """The prompt contains NO_IMAGE_VISIBLE; only the reply may be read.

        This is the exact false-completion bug that made an earlier version of
        the mutation test pass without the model having answered at all.
        """
        answer = _committed_answer(self._transcript("XYZ789"))
        assert answer == "XYZ789"
        assert "NO_IMAGE_VISIBLE" not in answer

    def test_reads_the_last_assistant_turn(self):
        transcript = self._transcript("first") + (
            "[ASSISTANT] - Aug 05, 9:00:20.000am\nsecond\n" + self.RULE + "\n"
        )
        assert _committed_answer(transcript) == "second"

    def test_detects_a_negative_answer(self):
        assert _committed_answer(self._transcript("NO_IMAGE_VISIBLE")) == "NO_IMAGE_VISIBLE"

    def test_log_noise_without_a_committed_turn_is_not_an_answer(self):
        """Raw agent logs echo the prompt but contain no session transcript."""
        noisy_log = (
            "[STARTUP] agent=x provider=claude-code\n"
            "-q Use the read_image tool ... reply NO_IMAGE_VISIBLE.\n"
            "[MCP_DIAG] tool_handler_entry tool=read_image\n"
        )
        assert _committed_answer(noisy_log) is None


@pytest.mark.skipif(not LIVE_GATE, reason="requires DEEPAGENTS_LIVE_IMAGE_TEST=1 and a Claude Code CLI")
class TestLiveAgentSeesImage:
    """#26/#27 — full lifecycle through the real seam.

    The agent is launched detached from this process's stdio. That detail is
    load-bearing: a daemon that inherits pytest's captured pipe blocks forever
    on its first large write (the base64 tool result), which looks exactly like
    a hang in the code under test but is purely a harness artefact.
    """

    def _history(self, agent_name: str, deadline: float) -> str:
        """Everything the agent has produced so far, from every channel.

        The session database is only written once a turn is committed, so it is
        useless as a progress signal while the agent is still thinking. The
        agent's own log files are appended live, so they are read as well and
        the two are concatenated.
        """
        parts: list[str] = []

        log_dir = deep_worker_home() / "logs"
        for suffix in (".out.log", ".err.log"):
            log_path = log_dir / f"{agent_name}{suffix}"
            try:
                parts.append(log_path.read_text(errors="replace"))
            except OSError:
                pass

        remaining = _remaining(deadline)
        if remaining > 0:
            try:
                result = subprocess.run(
                    ["deep-worker", "--history", agent_name],
                    capture_output=True,
                    text=True,
                    timeout=remaining,
                    check=False,
                )
                parts.append(result.stdout)
            except subprocess.TimeoutExpired:
                pass

        return "\n".join(parts)

    def _await_answer(self, agent_name: str, nonce: str, deadline: float) -> str:
        """Block until the agent commits an answer, or the shared deadline passes.

        Event-driven: an inotify watch on the log directory wakes this up only
        when the agent actually writes something. There is no retry timer and no
        fixed-interval re-reading -- `select` blocks with the remaining budget as
        its only timeout, so an idle agent costs nothing.
        """
        log_dir = deep_worker_home() / "logs"
        log_dir.mkdir(parents=True, exist_ok=True)

        transcript = self._history(agent_name, deadline)

        watcher = InotifyWatch(log_dir)
        if not watcher.supported:
            watcher.close()
            pytest.skip("inotify unavailable; refusing to fall back to polling")
        try:
            while not self._answered(transcript, nonce):
                remaining = _remaining(deadline)
                if remaining <= 0:
                    break
                if not watcher.wait(remaining):
                    break  # deadline expired with no further activity
                transcript = self._history(agent_name, deadline)
        finally:
            watcher.close()

        return transcript

    @staticmethod
    def _answered(transcript: str, nonce: str) -> bool:
        """True once the model has actually committed a reply."""
        answer = _committed_answer(transcript)
        if answer is None:
            return False
        return nonce in answer or "NO_IMAGE_VISIBLE" in answer

    def _run_agent(
        self,
        image_path: Path,
        agent_name: str,
        nonce: str,
        *,
        dev_tree_root: Path | None = None,
    ) -> str:
        """Run a bounded claude-code agent and return its transcript.

        ONE deadline governs the interaction -- launch, every `--history`
        subprocess and the answer wait all receive the time that is actually
        left, so those cannot exceed TOTAL_BUDGET_SECONDS however the individual
        steps behave. Teardown then runs OUTSIDE that deadline, under its own
        single shared budget of TERMINATE_GRACE_SECONDS: it must be allowed to
        complete even when the interaction has already overrun, or a wedged
        agent would be leaked. The wall-clock ceiling is therefore exactly
        TOTAL_BUDGET_SECONDS + TERMINATE_GRACE_SECONDS, and the agent is always
        torn down, so a stuck agent can neither hang the suite nor survive it.
        """
        deadline = time.monotonic() + TOTAL_BUDGET_SECONDS
        # The prompt must never contain the nonce, otherwise it would be echoed
        # into the logs we scan and produce a false pass.
        query = (
            f"Use the read_image tool on {image_path} and report the exact "
            "codeword shown in the image. Reply with the codeword only. "
            "If you cannot actually see the image, reply NO_IMAGE_VISIBLE."
        )
        assert nonce not in query
        cmd = [
            "deep-worker",
            agent_name,
            "--dev",
            "--provider",
            "claude-code",
            "--dir",
            str(image_path.parent),
            "-sp",
            "--no-task-manager",
            "-q",
            query,
        ]
        transcript = ""
        try:
            # The launcher daemonizes, and the daemon inherits whatever stdio it
            # is given. Under pytest that would be a captured pipe which nobody
            # drains, so the agent blocks forever on its first large write (the
            # base64 tool result). Detach it from our stdio entirely.
            # Strip pytest's own markers: the agent and the CLI beneath it are
            # ordinary programs, and libraries that branch on PYTEST_CURRENT_TEST
            # would otherwise take a different path here than in production.
            env = {k: v for k, v in os.environ.items() if not k.startswith("PYTEST")}
            if dev_tree_root is not None:
                # Documented launcher hook: dispatch --dev at an isolated copy
                # instead of the real worktree, which is never modified.
                env["DEEP_WORKER_DEV_TREE_ROOT_OVERRIDE"] = str(dev_tree_root)
                # The mutant package owns private cache directories, but suppress
                # bytecode entirely so a throwaway tree can never write into the
                # real one through some path we did not anticipate.
                env["PYTHONDONTWRITEBYTECODE"] = "1"
            with open(os.devnull, "wb") as devnull:
                subprocess.run(
                    cmd,
                    stdin=subprocess.DEVNULL,
                    stdout=devnull,
                    stderr=devnull,
                    timeout=max(1.0, min(LAUNCH_TIMEOUT_SECONDS, _remaining(deadline))),
                    check=False,
                    env=env,
                )

            # Wait for the agent's answer, blocking on filesystem events rather
            # than re-reading on a timer: the agent appends to its log file, so
            # inotify wakes us exactly when there is something new to look at.
            transcript = self._await_answer(agent_name, nonce, deadline)
            return transcript
        finally:
            self._terminate(agent_name)

    def _terminate(self, agent_name: str) -> None:
        """Stop exactly this agent: SIGTERM, then SIGKILL, by verified PID.

        Two things could go wrong and neither is acceptable in a test suite:
        a name-based `pkill -f` would match any command line merely mentioning
        the agent (including this very test process), and a recorded PID may
        have been recycled by the kernel for something else entirely. So the
        PID is re-verified against /proc/<pid>/cmdline immediately before every
        signal, and anything that is not this agent is left alone.

        Bounded by a single teardown deadline of TERMINATE_GRACE_SECONDS total,
        shared across both signals.
        """
        pid_file = Path(f"/tmp/deep_worker_{agent_name}.pid")  # noqa: S108 - set by the launcher
        try:
            pid = int(pid_file.read_text().strip())
        except (OSError, ValueError):
            return

        def is_target() -> bool:
            try:
                cmdline = Path(f"/proc/{pid}/cmdline").read_bytes()
            except OSError:
                return False  # process gone, or not ours to inspect
            args = cmdline.split(b"\0")
            # The agent name is a standalone argv entry, so this cannot be
            # satisfied by a substring of some unrelated command line.
            return agent_name.encode() in args

        # A pidfd becomes readable exactly when the process exits, so the wait
        # between SIGTERM and SIGKILL is event-driven rather than a retry loop.
        # It is opened BEFORE signalling, while identity is still verified, so
        # it can never refer to a later process that reuses this pid.
        pidfd = -1
        try:
            if is_target():
                try:
                    pidfd = os.pidfd_open(pid)  # type: ignore[attr-defined]
                except (AttributeError, OSError):
                    pidfd = -1

            # ONE deadline for the whole teardown, so escalating from SIGTERM to
            # SIGKILL cannot double the wait: both waits draw from the same
            # budget and the total is bounded by TERMINATE_GRACE_SECONDS.
            teardown_deadline = time.monotonic() + TERMINATE_GRACE_SECONDS
            for sig in (signal.SIGTERM, signal.SIGKILL):
                if not is_target():
                    break
                try:
                    os.kill(pid, sig)
                except OSError:
                    break
                if pidfd < 0:
                    # No pidfd: escalate straight to SIGKILL rather than
                    # reintroducing a polling loop.
                    continue
                readable, _, _ = select.select([pidfd], [], [], _remaining(teardown_deadline))
                if readable:
                    break  # exited
        finally:
            if pidfd >= 0:
                os.close(pidfd)
            pid_file.unlink(missing_ok=True)

    def test_model_reports_the_nonce_from_the_evicted_image(self) -> None:
        """The model must read a codeword it can only know by seeing the image."""
        nonce = _make_nonce()
        png = _render_nonce_png(nonce)

        # The agent daemonizes and resolves its working directory after this
        # function returns, so the image must live in a directory that is still
        # present then -- a TemporaryDirectory context would already be gone.
        workdir = Path(tempfile.mkdtemp(prefix="dgwork_"))
        try:
            workdir.chmod(0o755)
            image_path = workdir / "nonce.png"
            image_path.write_bytes(png)
            image_path.chmod(0o644)

            # Unique per run: a stale session database from an earlier run must
            # never be able to produce a false pass.
            agent_name = f"dgimg{nonce.lower()}"
            # _run_agent tears the agent down before returning, so the working
            # directory is only removed once nothing is using it as its cwd.
            transcript = self._run_agent(image_path, agent_name, nonce)
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

        # NOTE: the literal "NO_IMAGE_VISIBLE" also appears in the prompt we
        # sent, so scanning the raw transcript proves nothing. Read the committed
        # reply only. The nonce is the real evidence: it exists solely inside the
        # rendered bitmap, so a model that reports it must have seen the image.
        answer = _committed_answer(transcript)
        assert answer is not None, "agent produced no committed answer (crash or timeout?)"
        assert nonce in answer, f"model did not report the nonce {nonce!r}: {answer[:200]!r}"

    def test_mutation_disabling_preservation_blinds_the_model(self) -> None:
        """#27 — the live proof must be sensitive to this exact source change.

        The agent runs against a copy of the source tree in which image
        preservation is disabled (images are classified as evictable, i.e. the
        pre-fix behaviour). The same agent, same image and same prompt must then
        fail to report the nonce. Without this, #26 could be passing for reasons
        unrelated to the fix.
        """
        nonce = _make_nonce()
        png = _render_nonce_png(nonce)

        workdir = Path(tempfile.mkdtemp(prefix="dgwork_"))
        mutant_root = Path(tempfile.mkdtemp(prefix="dgmutroot_"))
        try:
            workdir.chmod(0o755)
            image_path = workdir / "nonce.png"
            image_path.write_bytes(png)
            image_path.chmod(0o644)

            _build_mutant_tree(mutant_root)
            transcript = self._run_agent(
                image_path,
                f"dgmut{nonce.lower()}",
                nonce,
                dev_tree_root=mutant_root,
            )
        finally:
            shutil.rmtree(workdir, ignore_errors=True)
            shutil.rmtree(mutant_root, ignore_errors=True)

        # A negative assertion alone would pass on a launch failure, a timeout,
        # an auth error or a crashed agent -- none of which say anything about
        # image preservation. Demand a positively committed answer first.
        answer = _committed_answer(transcript)
        assert answer is not None, "mutant agent produced no committed answer (crash or timeout?)"
        assert "NO_IMAGE_VISIBLE" in answer, f"unexpected mutant answer: {answer[:200]!r}"
        assert nonce not in answer, (
            "model still reported the nonce with image preservation disabled -- "
            "the live test is not actually sensitive to the fix"
        )


