"""Gated proof that an image survives eviction all the way to the model's eyes.

Design tests #26 and #27 of
`DESIGN_FIX_IMAGE_BLOCKS_SURVIVE_TOOL_RESULT_EVICTION.md`.

The point of this test is that it traverses the **real seam**:

    read_image tool result
      -> FilesystemMiddleware large-result eviction
      -> provider content conversion
      -> the model's vision

A direct SDK call that bypasses the middleware is explicitly *not* accepted as
proof, which is why the eviction step is exercised for real here.

The image is generated by the test itself using only the standard library
(`zlib` + `struct` raw PNG), so the test never depends on mutable files under
`~/tmp` and never needs Pillow. It renders a random codeword ("nonce") as blocky
glyphs; the model must read that codeword back. Because the nonce is fresh on
every run, a passing result cannot come from memorised content.

Requires a working Claude Code CLI, so it is gated behind
`DEEPAGENTS_LIVE_IMAGE_TEST=1` and skipped by default.
"""

